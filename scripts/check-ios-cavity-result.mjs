import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {parseScanResult} from '../src/scanning/contract.ts';
import {parseSavedGeometry} from '../src/scanning/saved-geometry.ts';
import {parseInteriorCavity} from '../src/scanning/interior-cavity.ts';
const fixture=JSON.parse(await readFile(process.argv[2],'utf8'));
const scan=parseScanResult(fixture.scan,'container_interior');
const source=parseSavedGeometry(fixture.preview,scan.record);
const result=parseInteriorCavity(fixture.cavity,source,fixture.review);
assert.equal(scan.record.platform,'ios');
assert.equal(result.cavity.freeCells.length,560);
assert.equal(result.cavity.opening.cells.length,80);
assert.equal(result.cavity.sourceHash,source.sourceHash);
assert.equal(result.surface.faceCount,result.cavity.surfaceFaceCount);
assert.ok(Math.abs(result.surface.volumeMm3-result.cavity.estimatedVolumeMm3)<1e-6);
assert.throws(()=>parseInteriorCavity({...fixture.cavity,sourceHash:'0'.repeat(64)},source,fixture.review));
assert.throws(()=>parseInteriorCavity(fixture.cavity,source,{...fixture.review,openingSign:-1}));
assert.throws(()=>parseInteriorCavity({...fixture.cavity,observedCells:fixture.cavity.observedCells.slice(1)},source,fixture.review));
assert.ok(!JSON.stringify(fixture).includes('file://'));
console.log('Swift/TypeScript interior result passed with actual encrypted-source synthetic output.');
